#!/usr/bin/env python3
"""mkui.py -- build the menu's bitmaps: src/uiart.h (font, icons, micro letters) and assets_gen/logo.img.

    mkui.py --picopak <PicoPak-SMS/menu> --logo <logo.png> [--out <menu dir>]

The 8x8 face is PicoPak-SMS's extraction of Press Start 2P (c) 2011 Cody "CodeMan38" Boisclair, SIL Open Font
License 1.1 (the bitmaps are a Modified Version: not to be called "Press Start"; OFL.txt ships on the disc).
The icons, the 3x5 micro letters and the pad-button shape are PicoPak-SMS's own drawings (menu/art.py), plus the
disc and wrench icons drawn for this menu.

logo.img: "OLG1", u16 w, u16 h, then h rows of w big-endian RGB555 pixels padded to a 4-byte row, then a 1-bpp
mask of the solid lettering (rows padded to 4 bytes) used by the optional shine. The logo is composited onto
the menu's background colour here.
"""
import argparse
import os
import struct
import sys

from PIL import Image

BG = (8, 2, 20)
LOGO_H = 24

EXTRA_ICONS = {
    'disc': ('..###...', '.#####..', '##...##.', '##.#.##.', '##...##.', '.#####..', '..###...', '........'),
    'wrench': ('.....##.', '....#...', '....#..#', '...####.', '..##....', '.##.....', '##......', '........'),
}
EXTRA_MICRO = {
    'A': ('###', '#.#', '###', '#.#', '#.#'), 'B': ('##.', '#.#', '##.', '#.#', '##.'),
    'D': ('##.', '#.#', '#.#', '#.#', '##.'), 'E': ('###', '#..', '##.', '#..', '###'),
    'I': ('###', '.#.', '.#.', '.#.', '###'), 'L': ('#..', '#..', '#..', '#..', '###'),
    'N': ('##.', '#.#', '#.#', '#.#', '#.#'), 'O': ('###', '#.#', '#.#', '#.#', '###'),
    'P': ('###', '#.#', '###', '#..', '#..'), 'R': ('##.', '#.#', '##.', '#.#', '#.#'),
    'U': ('#.#', '#.#', '#.#', '#.#', '###'),
}
ICON_ORDER = ['folder', 'up', 'disc', 'heart', 'clock', 'wrench', 'gear', 'info']


def disc_rings():
    """the 'no art' disc: ring (DIM) and body (EDGE), 44x44, as in mock_art.var_noart"""
    ring, body = [], []
    for y in range(44):
        r1, r2 = '', ''
        for x in range(44):
            dx, dy = x - 22 + 0.5, y - 22 + 0.5
            d = dx * dx + dy * dy
            r1 += '#' if 19 ** 2 < d <= 22 ** 2 else '.'
            r2 += '#' if 5 ** 2 < d <= 19 ** 2 else '.'
        ring.append(r1)
        body.append(r2)
    return ring, body


def c_sprite(name, rows):
    w, h = len(rows[0]), len(rows)
    bpr = (w + 7) // 8
    data = []
    for r in rows:
        bits = r.ljust(bpr * 8, '.')
        for k in range(bpr):
            v = 0
            for i in range(8):
                if bits[k * 8 + i] == '#':
                    v |= 0x80 >> i
            data.append(v)
    return w, h, data


def q5(v):
    return max(0, min(31, (v + 4) >> 3))


def build_logo(path, out):
    src = Image.open(path).convert('RGBA')
    box = src.getchannel('A').point(lambda v: 255 if v > 90 else 0).getbbox()
    src = src.crop(box)
    w = round(src.width * LOGO_H / src.height)
    lg = src.resize((w, LOGO_H), Image.LANCZOS)
    stride = (w * 2 + 3) & ~3
    mstride = ((w + 31) // 32) * 4
    pix = bytearray()
    mask = bytearray()
    for y in range(LOGO_H):
        row = bytearray()
        mrow = bytearray(mstride)
        for x in range(w):
            r, g, b, a = lg.getpixel((x, y))
            t = a / 255.0
            c = [int(r * t + BG[0] * (1 - t)), int(g * t + BG[1] * (1 - t)), int(b * t + BG[2] * (1 - t))]
            v = (q5(c[0]) << 10) | (q5(c[1]) << 5) | q5(c[2])
            row += struct.pack('>H', v or 1)
            if a > 120:
                mrow[x >> 3] |= 0x80 >> (x & 7)
        pix += row.ljust(stride, b'\0')
        mask += mrow
    with open(out, 'wb') as f:
        f.write(b'OLG1' + struct.pack('>HH', w, LOGO_H) + pix + mask)
    return w


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--picopak', required=True)
    ap.add_argument('--logo', required=True)
    ap.add_argument('--out', default=os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
    a = ap.parse_args()
    sys.path.insert(0, a.picopak)
    sys.path.insert(0, os.path.join(a.picopak, 'tools'))
    import art as A
    import font_ps2p as F8

    lines = ['/* uiart.h -- GENERATED by tools/mkui.py; rebuild rather than edit.',
             ' *',
             ' * FONT8: an 8x8 face extracted from Press Start 2P (by way of PicoPak-SMS menu/tools/font_ps2p.py).',
             ' *   Copyright (c) 2011, Cody "CodeMan38" Boisclair, with Reserved Font Name Press Start.',
             ' *   Licensed under the SIL Open Font License 1.1 (OFL.txt on the disc). This is a Modified Version',
             ' *   and is not called Press Start.',
             ' * Icons, the 3x5 micro letters and the pad button: PicoPak-SMS menu/art.py drawings, plus disc/wrench.',
             ' */',
             '#ifndef UIART_H', '#define UIART_H', '',
             '#define FONT8_FIRST 0x20', '#define FONT8_LAST  0x5f', '']
    data = ['#ifdef UIART_DATA', '', 'static const uint8 font8[64][8] = {']
    for c in range(0x20, 0x60):
        rows = A.menu_rows(chr(c), F8)
        data.append('    {%s},' % ', '.join('0x%02x' % r for r in rows))
    data.append('};')
    data.append('')

    sprites = []
    icons = dict(A.ICONS)
    icons.update(EXTRA_ICONS)
    for n in ICON_ORDER:
        sprites.append(('ICON_' + n.upper(), icons[n]))
    sprites.append(('SPR_BUTTON', A.BUTTON))
    micro = dict(A.MICRO)
    micro.update(EXTRA_MICRO)
    mletters = sorted(k for k in micro if 'A' <= k <= 'Z')
    for k in mletters:
        sprites.append(('MICRO_' + k, micro[k]))
    ring, body = disc_rings()
    sprites.append(('SPR_DISC_RING', ring))
    sprites.append(('SPR_DISC_BODY', body))

    lines.append('enum {')
    for i, (n, _) in enumerate(sprites):
        lines.append('    %s = %d,' % (n, i))
    lines.append('    SPRITE_COUNT = %d' % len(sprites))
    lines.append('};')
    lines.append('')
    data.append('/* micro letter sprite for A..Z, or -1 */')
    data.append('static const int8 micro_index[26] = {%s};' % ', '.join(
        ('MICRO_' + chr(65 + i)) if chr(65 + i) in mletters else '-1' for i in range(26)))
    data.append('')
    blob, table = [], []
    for n, rows in sprites:
        w, h, d = c_sprite(n, rows)
        table.append('    {%d, %d, %d},  /* %s */' % (w, h, len(blob), n))
        blob += d
    data.append('typedef struct { uint8 w, h; uint16 off; } SpriteDef;')
    data.append('static const SpriteDef sprite_defs[SPRITE_COUNT] = {')
    data += table
    data.append('};')
    data.append('static const uint8 sprite_bits[%d] = {' % len(blob))
    for k in range(0, len(blob), 16):
        data.append('    ' + ', '.join('0x%02x' % v for v in blob[k:k + 16]) + ',')
    data.append('};')
    data.append('')
    data.append('#endif /* UIART_DATA */')
    lines += [''] + data
    lines.append('')
    lines.append('#endif')
    with open(os.path.join(a.out, 'src', 'uiart.h'), 'w') as f:
        f.write('\n'.join(lines) + '\n')
    os.makedirs(os.path.join(a.out, 'assets_gen'), exist_ok=True)
    w = build_logo(a.logo, os.path.join(a.out, 'assets_gen', 'logo.img'))
    print('uiart.h: %d sprites; logo.img %dx%d' % (len(sprites), w, LOGO_H))


if __name__ == '__main__':
    main()
