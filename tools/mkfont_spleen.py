#!/usr/bin/env python3
"""Generate src/font_sp.h from Spleen 5x8 (BSD-2-Clause, Frederic Cambus).
   Usage: mkfont_spleen.py spleen-5x8.bdf > src/font_sp.h
   Format mirrors font5.h: 8 rows per glyph, 5 bits left-aligned at bit 7, chars 0x20..0x5f."""
import sys

def load(path):
    glyphs={}; fbb=None; cur=None; inb=False
    for ln in open(path, encoding='latin-1'):
        t=ln.split()
        if not t: continue
        if t[0]=='FONTBOUNDINGBOX': fbb=tuple(map(int,t[1:5]))
        elif t[0]=='STARTCHAR': cur={'bits':[]}
        elif t[0]=='ENCODING': cur['cp']=int(t[1])
        elif t[0]=='BBX': cur['bbx']=tuple(map(int,t[1:5]))
        elif t[0]=='BITMAP': inb=True
        elif t[0]=='ENDCHAR': inb=False; glyphs[cur['cp']]=cur
        elif inb: cur['bits'].append(int(t[0],16))
    return glyphs, fbb

def cell(g, fbb):
    W,Hh=5,8
    fbb_asc=fbb[1]+fbb[3]            # ascent above baseline
    rows=[0]*Hh
    w,h,xo,yo=g['bbx']
    off=fbb_asc-(h+yo)              # top row of glyph within the 8-tall cell
    rb=(w+7)//8
    for ry in range(h):
        cr=off+ry
        if cr<0 or cr>=Hh: continue
        val=g['bits'][ry] if ry<len(g['bits']) else 0
        val >>= (rb*8-w)
        for c in range(w):
            if val&(1<<(w-1-c)):
                cc=xo+c
                if 0<=cc<W: rows[cr]|=0x80>>cc
    return rows

def main():
    glyphs,fbb=load(sys.argv[1])
    print('/* font_sp.h - Spleen 5x8 (BSD-2-Clause, Copyright (c) 2018-2026 Frederic Cambus, https://www.cambus.net/).')
    print(' * Bitmap bundled under BSD-2-Clause; see SPLEEN-LICENSE on the disc. 8 rows, 5 bits each, left-aligned at')
    print(' * bit 7. GENERATED by tools/mkfont_spleen.py; rebuild rather than edit. */')
    print('#define FONTSP_FIRST 0x20')
    print('#define FONTSP_LAST  0x5f')
    print('#define FONTSP_H     8')
    print('static const uint8 font_sp[64][8] = {')
    for cp in range(0x20,0x60):
        g=glyphs.get(cp)
        rows=cell(g,fbb) if g else [0]*8
        ch=chr(cp); label=ch if ch not in '\\' else '\\\\'
        print('    {'+', '.join('0x%02X'%b for b in rows)+'}, /* %s */'%label)
    print('};')

main()
